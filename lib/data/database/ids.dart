import 'dart:math';

final Random _random = Random.secure();

/// Generates a UUID-v4-shaped, export-safe identifier.
///
/// Flind deliberately avoids a UUID package for this single need: the value is
/// opaque, random and stable once written. It is not used as a database key;
/// integer row ids remain internal, while these values survive export/import
/// and future multi-device sync.
String newPublicId() {
  final bytes = List<int>.generate(16, (_) => _random.nextInt(256));

  // RFC 4122 version/variant bits: v4, variant 10xx.
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;

  String hex(int start, int end) => bytes
      .sublist(start, end)
      .map((b) => b.toRadixString(16).padLeft(2, '0'))
      .join();

  return '${hex(0, 4)}-${hex(4, 6)}-${hex(6, 8)}-${hex(8, 10)}-${hex(10, 16)}';
}
